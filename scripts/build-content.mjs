import fs from 'node:fs/promises';
import path from 'node:path';

// Only explicitly public files are included. Never scan the repository or .env.
export async function buildContentBundle(projectRoot, posts) {
  const files = ['data/resources.json', 'projects/heart-matrix/heart_matrix/heart_matrix.ino',
    ...posts.map(post => `posts/${post.slug}.md`)];
  const content = Object.fromEntries(await Promise.all(files.map(async file =>
    [file, await fs.readFile(path.join(projectRoot, file), 'utf8')])));
  content['posts/index.json'] = JSON.stringify(posts);
  const serialized = JSON.stringify(content).replaceAll('<', '\\u003c')
    .replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029');
  const script = `// Generated by node scripts/build-posts.mjs. Edit the source files, then rebuild.
(() => {
  'use strict';
  const files = ${serialized};
  async function readText(file) {
    if (location.protocol === 'file:') {
      const key = decodeURIComponent(file.replace(/^\\.\\//, ''));
      if (!Object.hasOwn(files, key)) throw new Error('找不到这份内容。');
      return files[key];
    }
    const response = await fetch(file, { cache: 'no-store' });
    if (!response.ok) throw new Error('内容读取失败（HTTP ' + response.status + '）。');
    return response.text();
  }
  window.SparkContent = Object.freeze({ readText, readJSON: async file => JSON.parse(await readText(file)) });
})();
`;
  await fs.writeFile(path.join(projectRoot, 'site-content.js'), script);
}
